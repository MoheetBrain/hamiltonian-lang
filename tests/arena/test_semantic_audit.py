def test_E_oracle_answer_is_literally_shared_by_all_arms():
    """One item, one key. The arms cannot be scored against different truths."""
    from evaluation.arena.endpoints import contrast
    from evaluation.arena.endpoints.common import build_prompt
    from evaluation.arena.run_screen import _INSTRUCTIONS, build_dev_pairs

    pairs = build_dev_pairs("PILOT", "L3", 2, contrast.CONTRASTS)
    for a, b in pairs:
        for item in (a, b):
            keys = {arm: item.answer for arm in ARMS}
            assert len(set(keys.values())) == 1
            spaces = {arm: item.answer_space for arm in ARMS}
            assert len(set(spaces.values())) == 1
            # And the three prompts really are three renderings of one item.
            texts = {
                arm: build_prompt(item, ARM_RENDERERS[arm], instructions=_INSTRUCTIONS)
                for arm in ARMS
            }
            assert len(set(texts.values())) == 3


