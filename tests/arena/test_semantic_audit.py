@pytest.mark.parametrize("family", sorted(FAMILIES))
def test_C_no_pilot_construct_can_be_undefined(family):
    """No division, so definedness is never a side condition in any pilot item."""
    for s in SEEDS:
        w = generate(family, "L3", s)
        for f in w.facts:
            assert "/" not in canonical(f.prop).replace("(num ", ""), (
                f"{w.world_id}: a partial operation reached a pilot construct"
            )


