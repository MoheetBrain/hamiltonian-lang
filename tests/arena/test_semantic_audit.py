"""Literature-derived semantic audit: are the *observable semantics* arm-invariant?

Read-only and test-only. Nothing in `evaluation/arena/` is modified by this audit, and no
model-visible prompt, difficulty, scoring rule or task semantics changes -- doing so after
model selection would invalidate the selection and force it to be repeated.

**The judgment classes are kept separate.** The governing distinction is that
PARSES / TYPECHECKS / HAS_DEFINED_DENOTATION / IS_SEMANTICALLY_EQUIVALENT / IS_ENTAILED /
EXECUTES / IS_PROVEN are *different* judgments, and collapsing them into one `VALID` flag
is the error to avoid. What the arena needs before the pilot is narrower than all seven:

- **PARSES** — every HML rendering parses under the real compiler.
- **TYPECHECKS** — every HML rendering type-checks under the real compiler.
- **IS_SEMANTICALLY_EQUIVALENT** — the three arms denote the same world. This is what the
  round-trip identity already establishes; the tests below check the *specific* semantic
  properties the pilot depends on, rather than re-proving the whole identity.
- **IS_ENTAILED / oracle truth** — the answer key is a property of the world, not of the
  arm, and must be literally shared.

**Not** audited here, deliberately, with reasons:

- **EXECUTES** — the arena has no evaluation semantics for a model-visible program. Nothing
  in the Endpoint-B pilot executes.
- **IS_PROVEN / obligations** — the pilot uses no `derive`/`goal` chains, so no proof
  obligations are generated by any pilot item. Recorded as not-applicable rather than
  silently skipped; it becomes live for the next-action endpoint.
- **HAS_DEFINED_DENOTATION** — partiality cannot arise: the world generator emits no
  division and no other partial operation, so no term can be undefined. Asserted below
  rather than assumed.

The existing 1800/1800 round-trip result stands as evidence and is not replaced.
"""

from __future__ import annotations

import re

import pytest
from evaluation.arena.decoders import decode_ast, decode_english, decode_hml
from evaluation.arena.ir import BVar, Conn, Elem, Quant, canonical, walk
from evaluation.arena.parity import ARM_RENDERERS
from evaluation.arena.worlds import FAMILIES, canonical_world, generate

SEEDS = range(200_001, 200_009)
ARMS = ("SE", "AST", "HML")
DECODERS = {"SE": decode_english, "AST": decode_ast, "HML": decode_hml}


def _roundtrip(w, arm):
    r = ARM_RENDERERS[arm]
    return DECODERS[arm](r.state(w), r.question(w), w.family)


# ---------------------------------------------------------------------------
# A. PARSES  and  B. TYPECHECKS -- separate judgments, checked separately
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("family", sorted(FAMILIES))
def test_A_hml_arm_parses(family):
    from hamiltonian_lang.parser import parse

    r = ARM_RENDERERS["HML"]
    for s in SEEDS:
        w = generate(family, "L3", s)
        _, bag = parse(r.compilable(w), f"<{w.world_id}>")
        assert bag.ok, f"{w.world_id} does not PARSE: {[d.code for d in bag.errors][:3]}"


@pytest.mark.parametrize("family", sorted(FAMILIES))
def test_B_hml_arm_typechecks(family):
    """Distinct from parsing: a file can parse and still fail name/type resolution."""
    from hamiltonian_lang import compile_source

    r = ARM_RENDERERS["HML"]
    for s in SEEDS:
        w = generate(family, "L3", s)
        res = compile_source(r.compilable(w), f"<{w.world_id}>")
        assert res.ok(), f"{w.world_id} does not TYPECHECK:\n{res.diagnostics.render()}"


