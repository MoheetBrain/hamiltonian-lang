"""Property-based tests for alpha-equivalence of the canonical form.

The claim under test, from ``docs/design/V0_DESIGN_FREEZE.md`` §5::

    Consequence, and a v0 success criterion: alpha-renaming a program must not change its
    canonical hash.

and from ``src/hamiltonian_lang/backends/canonical.py``::

    Two programs that differ only by variable spelling, blank lines, or comments must
    produce byte-identical canonical JSON and therefore the same hash.

Two properties, in both directions, because only testing one is how a broken
canonicaliser passes:

* **P1 (invariance)** — rename every binder and every reference *consistently*, and the
  content hash must not change.
* **P2 (discrimination)** — rename *inconsistently*, so that the program's binding
  structure genuinely changes, and the hash must change. A canonicaliser that maps
  everything to a constant satisfies P1 perfectly and is useless.

Programs are generated by hypothesis from a small grammar of module-level declarations,
definitions, constraints, quantified propositions and distribution laws, so the generated
inputs cover the binder forms the language actually has rather than one hand-picked case.
"""

from __future__ import annotations

import re
import string

import pytest
from hypothesis import HealthCheck, assume, given, settings
from hypothesis import strategies as st

from hamiltonian_lang import compile_source

SETTINGS = settings(
    max_examples=200,
    deadline=None,
    suppress_health_check=[HealthCheck.too_slow],
)

# Identifiers are drawn from disjoint pools so a rename can never accidentally collide
# with a name already in the program, which would turn a rename into a capture and make a
# hash change correct rather than a defect.
POOL_A = ["alpha", "beta", "gamma", "delta", "epsilon", "zeta"]
POOL_B = ["kappa", "lambda_", "mu_", "nu_", "xi_", "omicron"]

RESERVED = {
    "module", "var", "param", "const", "obs", "index", "rv", "def", "fn", "law", "prior",
    "likelihood", "assume", "require", "prove", "minimise", "maximise", "solve", "infer",
    "check", "concept", "end", "extends", "forall", "exists", "unique", "and", "or",
    "not", "implies", "iff", "true", "false", "dimension", "posterior", "expectation",
    "variance", "mle", "map", "parameter", "transform", "invariant", "property",
    "example", "counterexample",
}


# ---------------------------------------------------------------------------
# Generators
# ---------------------------------------------------------------------------

names = st.lists(st.sampled_from(POOL_A), min_size=2, max_size=4, unique=True)
scalars = st.sampled_from(["Real", "PositiveReal", "NonNegativeReal", "Probability"])
comparisons = st.sampled_from([">", ">=", "<", "<=", "="])
arith = st.sampled_from(["+", "-", "*"])
quantifiers = st.sampled_from(["forall", "exists"])


@st.composite
def declaration_program(draw) -> str:
    """Module-level declarations plus a constraint that references them."""
    ns = draw(names)
    lines = ["module Generated", ""]
    for n in ns:
        lines.append(f"var {n} : Real")
    lines.append("")
    op = draw(comparisons)
    a = draw(arith)
    lines.append(f"require {ns[0]} {a} {ns[1]} {op} 0.0")
    return "\n".join(lines) + "\n"


@st.composite
def definition_program(draw) -> str:
    """Definitions form a dependency chain, so renaming must propagate through it."""
    ns = draw(names)
    assume(len(ns) >= 3)
    lines = ["module Generated", "", f"param {ns[0]} : Real", f"param {ns[1]} : Real", ""]
    a1, a2 = draw(arith), draw(arith)
    lines.append(f"def {ns[2]} := {ns[0]} {a1} {ns[1]}")
    if len(ns) >= 4:
        lines.append(f"def {ns[3]} := {ns[2]} {a2} {ns[0]}")
    return "\n".join(lines) + "\n"


@st.composite
def quantifier_program(draw) -> str:
    """Nested quantifiers: the binder form the canonical projection is designed for."""
    ns = draw(names)
    assume(len(ns) >= 2)
    q1, q2 = draw(quantifiers), draw(quantifiers)
    op = draw(comparisons)
    return (
        "module Generated\n\n"
        f"require {q1} {ns[0]} : Real . {q2} {ns[1]} : Real . {ns[1]} {op} {ns[0]}\n"
    )


@st.composite
def law_program(draw) -> str:
    """A distribution law, so role-labelled arguments are covered too."""
    ns = draw(names)
    assume(len(ns) >= 3)
    loc, scale, rv = ns[0], ns[1], ns[2]
    return (
        "module Generated\n\n"
        f"param {loc} : Real\n"
        f"param {scale} : PositiveReal\n"
        f"var {rv} : RandomVariable[Real]\n\n"
        f"law {rv} ~ Normal(location := {loc}, scale := {scale})\n"
    )


programs = st.one_of(
    declaration_program(), definition_program(), quantifier_program(), law_program()
)


# ---------------------------------------------------------------------------
# Renaming
# ---------------------------------------------------------------------------

_IDENT = re.compile(r"\b[A-Za-z_][A-Za-z0-9_]*\b")


def _role_label_spans(source: str) -> set[int]:
    """Start offsets of distribution ROLE LABELS, which are not renameable binders.

    ``location`` in ``Normal(location := mu, ...)`` is part of the language's vocabulary,
    not a symbol the program binds. Renaming it is not alpha-conversion; it produces a
    different (and invalid) program. Role labels are exactly the identifiers that sit at
    parenthesis depth >= 1 and are immediately followed by ``:=``.
    """
    out: set[int] = set()
    depth = 0
    for m in re.finditer(r"[()]|[A-Za-z_][A-Za-z0-9_]*|:=", source):
        tok = m.group(0)
        if tok == "(":
            depth += 1
        elif tok == ")":
            depth = max(0, depth - 1)
        elif depth >= 1 and tok not in ("(", ")", ":="):
            rest = source[m.end():]
            if rest.lstrip().startswith(":="):
                out.add(m.start())
    return out


def user_identifiers(source: str) -> list[str]:
    """Identifiers the program binds, in first-appearance order.

    Excludes reserved words, type and distribution-family names (capitalised, and the
    generators only ever mint lowercase user names) and distribution role labels.
    """
    roles = _role_label_spans(source)
    seen: list[str] = []
    for m in _IDENT.finditer(source):
        tok = m.group(0)
        if m.start() in roles:
            continue
        if tok in RESERVED or tok[0] in string.ascii_uppercase or tok in seen:
            continue
        seen.append(tok)
    return seen


def rename_all(source: str, mapping: dict[str, str]) -> str:
    """Consistent rename: every occurrence of every key is replaced simultaneously.

    Role labels are left alone, so this really is alpha-conversion and not a rewrite of
    the language's own vocabulary.
    """
    roles = _role_label_spans(source)

    def sub(m: re.Match) -> str:
        if m.start() in roles:
            return m.group(0)
        return mapping.get(m.group(0), m.group(0))

    return _IDENT.sub(sub, source)


def renameable_occurrences(source: str, old: str) -> list[re.Match]:
    roles = _role_label_spans(source)
    return [m for m in _IDENT.finditer(source)
            if m.group(0) == old and m.start() not in roles]


def rename_one_occurrence(source: str, old: str, new: str, index: int) -> str:
    """Inconsistent rename: replace exactly the ``index``-th occurrence of ``old``.

    This is what breaks the binding structure: one occurrence now names something else.
    """
    hits = renameable_occurrences(source, old)
    if index >= len(hits):
        return source
    m = hits[index]
    return source[: m.start()] + new + source[m.end():]


def hash_of(source: str) -> str | None:
    result = compile_source(source)
    return result.hash() if result.ok() else None


# ---------------------------------------------------------------------------
# P1 — consistent renaming preserves the hash
# ---------------------------------------------------------------------------


@pytest.mark.adversarial
@SETTINGS
@given(source=programs)
def test_consistent_renaming_preserves_the_content_hash(source: str):
    idents = user_identifiers(source)
    assume(idents)
    mapping = {old: POOL_B[i % len(POOL_B)] for i, old in enumerate(idents)}
    assume(len(set(mapping.values())) == len(mapping))  # no accidental capture

    renamed = rename_all(source, mapping)
    assume(renamed != source)

    h1, h2 = hash_of(source), hash_of(renamed)
    assume(h1 is not None)
    assert h2 is not None, (
        "the renamed program failed to compile, so the rename was not alpha-conversion:\n"
        + renamed
    )
    assert h1 == h2, (
        "consistent alpha-renaming changed the content hash, violating the v0 success "
        "criterion in docs/design/V0_DESIGN_FREEZE.md section 5\n"
        f"--- original ---\n{source}\n--- renamed ---\n{renamed}"
    )


@pytest.mark.adversarial
@SETTINGS
@given(source=programs)
def test_renaming_is_idempotent_under_a_round_trip(source: str):
    """Rename A->B then B->A and the hash must return to where it started."""
    idents = user_identifiers(source)
    assume(idents)
    fwd = {old: POOL_B[i % len(POOL_B)] for i, old in enumerate(idents)}
    assume(len(set(fwd.values())) == len(fwd))
    back = {v: k for k, v in fwd.items()}

    h0 = hash_of(source)
    assume(h0 is not None)
    there = rename_all(source, fwd)
    andback = rename_all(there, back)
    assert hash_of(andback) == h0


@pytest.mark.adversarial
@SETTINGS
@given(source=programs, pad=st.integers(min_value=0, max_value=4))
def test_comments_and_blank_lines_do_not_change_the_hash(source: str, pad: int):
    h0 = hash_of(source)
    assume(h0 is not None)
    noisy = ("\n" * pad) + "# a comment that carries no meaning\n" + source.replace(
        "\n", "\n" * (1 + (pad % 2))
    )
    assert hash_of(noisy) == h0


# ---------------------------------------------------------------------------
# P2 — inconsistent renaming changes the hash (or is rejected)
# ---------------------------------------------------------------------------


@pytest.mark.adversarial
@SETTINGS
@given(source=programs, which=st.integers(min_value=0, max_value=6))
def test_inconsistent_renaming_changes_the_hash_or_is_rejected(source: str, which: int):
    """Rename ONE occurrence of one identifier.

    Either the program stops compiling (the occurrence is now unbound, which is the
    correct outcome for a reference) or it compiles as a genuinely different program and
    must hash differently. What must never happen is that it compiles to the SAME hash:
    that would mean the canonical form is blind to a real change in binding structure.
    """
    idents = user_identifiers(source)
    assume(idents)
    old = idents[which % len(idents)]
    new = "renamed_only_here"

    occurrences = renameable_occurrences(source, old)
    assume(len(occurrences) >= 2)  # a single occurrence would be a consistent rename
    mutated = rename_one_occurrence(source, old, new, which % len(occurrences))
    assume(mutated != source)

    h0 = hash_of(source)
    assume(h0 is not None)
    h1 = hash_of(mutated)
    if h1 is None:
        return  # rejected: correct
    assert h1 != h0, (
        "an inconsistent rename produced the same canonical hash; the canonical form "
        "does not distinguish two different binding structures\n"
        f"--- original ---\n{source}\n--- mutated ---\n{mutated}"
    )


@pytest.mark.adversarial
@SETTINGS
@given(source=quantifier_program())
def test_swapping_quantifier_order_changes_the_hash(source: str):
    """Not a renaming property, but the discrimination property H2 depends on.

    Swapping ``forall``/``exists`` in a nested prefix must change the object. Included
    here because it is the same failure mode as P2: a canonicaliser that normalises away a
    meaning-bearing difference.
    """
    if "forall" not in source or "exists" not in source:
        return
    swapped = source.replace("forall", "\x00").replace("exists", "forall").replace(
        "\x00", "exists"
    )
    h0, h1 = hash_of(source), hash_of(swapped)
    assume(h0 is not None and h1 is not None)
    assert h0 != h1, f"quantifier order was normalised away\n{source}\n{swapped}"


