@pytest.mark.adversarial
# Was xfail(strict=True) for red-team finding 1.9.. The defect was
# fixed by the Lead Architect in the same session; the strict marker did its
# job by turning the fix into a visible failure. See DECISIONS.md D-016.
def test_definition_parameter_renaming_preserves_the_hash():
    a = "module M\ndef f(u : Real) : Real := u + 1.0\n"
    b = "module M\ndef f(w : Real) : Real := w + 1.0\n"
    assert hash_of(a) == hash_of(b), (
        "renaming a definition's formal parameter changed the content hash"
    )


@pytest.mark.adversarial
def test_module_level_declaration_renaming_preserves_the_hash():
    """Regression guard. This case DID fail earlier in the session and now passes;
    pinning it means a reintroduction is caught rather than rediscovered."""
    a = "module M\nvar alpha : Real\nrequire alpha > 0.0\n"
    b = "module M\nvar omega : Real\nrequire omega > 0.0\n"
    assert hash_of(a) == hash_of(b)


@pytest.mark.adversarial
def test_definition_name_renaming_preserves_the_hash():
    a = "module M\nparam a : Real\ndef total := a + 1.0\nrequire total > 0.0\n"
    b = "module M\nparam a : Real\ndef grand := a + 1.0\nrequire grand > 0.0\n"
    assert hash_of(a) == hash_of(b)


@pytest.mark.adversarial
def test_the_module_name_is_part_of_identity():
    """The converse guard: renaming the MODULE must change the hash, because the module
    name is not a bound variable. Without this, P1 could be satisfied by discarding it."""
    a = "module Alpha\nvar x : Real\n"
    b = "module Omega\nvar x : Real\n"
    assert hash_of(a) != hash_of(b)
