"""Claim resolution, rule checking, obligation discharge, and goal adjudication.

This is the pass that turns the V2 statement forms from notation into enforcement. It
runs after name resolution and type checking, because the kernel compares conclusions
under canonical identity and canonical identity includes resolved types.

Order of business, and why:

1. **Resolve claims.** Labels get :class:`ClaimId`s; premise references are resolved
   against the claim namespace; forward references and cycles are rejected. A
   derivation whose premises are not all established *before* it cannot be checked, so
   this has to come first.
2. **Build Γ from assumptions**, in statement order.
3. **Apply the kernel** to each derivation and set its status.
4. **Discharge obligations** against Γ.
5. **Adjudicate ``proved`` claims.**

The invariant the whole design rests on: nothing in this file sets
``DerivationStatus.VERIFIED`` except :meth:`_finalise_status`, and that method sets it
only when the kernel returned ``ok`` *and* every mandatory obligation is DISCHARGED.
"""

