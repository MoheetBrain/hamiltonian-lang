class ObligationStatus:
    OPEN = "OPEN"
    DISCHARGED = "DISCHARGED"
    FAILED = "FAILED"
    UNKNOWN = "UNKNOWN"

    ALL = (OPEN, DISCHARGED, FAILED, UNKNOWN)


@dataclass
class ReasoningObligation:
    """A side condition generated by a rule application.

    ``discharged_by`` names the claim label of the assumption that established it, so
    the provenance question "why is this allowed?" always has an answer that points at
    something the author wrote.
    """

    id: str
    proposition: Expr
    generated_by: str
    reason: str
    mandatory: bool
    status: str = ObligationStatus.OPEN
    discharged_by: str | None = None

    def to_dict(self) -> dict:
        from ..backends.hml import render_expr

        return {
            "id": self.id,
            "proposition": render_expr(self.proposition),
            "generated_by": self.generated_by,
            "reason": self.reason,
            "mandatory": self.mandatory,
            "status": self.status,
            "discharged_by": self.discharged_by,
        }


@dataclass
class ReasoningResult:
    obligations: list[ReasoningObligation] = field(default_factory=list)
    #: claim label -> derivation status, for reporting and for the CLI.
    derivation_status: dict[str, str] = field(default_factory=dict)
    goal_status: dict[str, str] = field(default_factory=dict)
    #: claim label -> EvidenceStatus, for `evidence` statements.
    evidence_status: dict[str, str] = field(default_factory=dict)
    #: goal label -> the context-relative judgment. This is the source of truth;
    #: ``goal_status`` is its projection. See reasoning/adjudication.py.
    adjudications: dict[str, Adjudication] = field(default_factory=dict)

    def verified(self) -> list[str]:
        return [k for k, v in self.derivation_status.items() if v == DerivationStatus.VERIFIED]

    def open_obligations(self) -> list[ReasoningObligation]:
        return [o for o in self.obligations if o.status == ObligationStatus.OPEN]

    def underdetermined(self) -> list[str]:
        return [
            g
            for g, a in self.adjudications.items()
            if a.verdict is EntailmentVerdict.UNDERDETERMINED
        ]


#: Statement forms that introduce a claim label into the claim namespace.
_LABELLED = (AssumeStmt, RequireStmt, ProveStmt, GoalStmt, DeriveStmt, EvidenceStmt)


def _unestablished_kind(st: Statement) -> str:
    """What to call a claim that may not be a premise, for the diagnostic.

    ``EvidenceStmt`` appears here in two quite different situations -- a rejected
    certificate, and a *valid* non-entailment result -- and they deserve different words.
    Calling the second one "rejected evidence" would be actively misleading: the
    certificate is fine, it simply does not assert the proposition.
    """
    if isinstance(st, GoalStmt):
        return "goal"
    if isinstance(st, RequireStmt):
        return "requirement"
    if isinstance(st, ProveStmt):
        return "claim"
    if isinstance(st, EvidenceStmt):
        if st.status == EvidenceStatus.VALID:
            return "non-entailment result"
        return "rejected certificate"
    return "claim"


def _checker_registry() -> dict:
    from .certificates import CHECKERS

    return CHECKERS


def _checker_names() -> tuple[str, ...]:
    from .certificates import checker_names

    return checker_names()


class _ReasoningChecker:
    def __init__(
        self, module: Module, diags: DiagnosticBag, symbols: object = None
    ) -> None:
        self.module = module
        self.diags = diags
        self.symbols = symbols
        self.result = ReasoningResult()
        #: label -> (statement, ClaimId)
        self.claims: dict[str, tuple[Statement, ClaimId]] = {}
        #: label -> the proposition a claim asserts, for claims usable as premises.
        #:
        #: NOTE ON THE NAME. This pool holds both ESTABLISHED claims (assumptions, and
        #: derivations the kernel VERIFIED) and PROVISIONAL ones (derivations that are
        #: CHECKED with an open obligation). A CHECKED claim is **not** established, and
        #: the earlier comment here called it that. It may be used, but only by passing
        #: its unresolved obligations along -- which `self.pending` does and
        #: `EvidenceGraph.effective_class` now states explicitly.
        self.propositions: dict[str, Expr] = {}
        #: label -> the statement, for claims that state something to be SHOWN
        #: (`goal`, `require`, `prove`). Kept only so a diagnostic can explain why
        #: citing one as a premise is refused, rather than saying "unknown claim".
        self.unestablished: dict[str, Statement] = {}
        #: label -> undischarged mandatory obligations inherited by anything citing it.
        self.pending: dict[str, list[ReasoningObligation]] = {}
        self.env = RefinementEnv()
        #: label -> the envelope a VALID `evidence` statement produced, for adjudication.
        self.certificates: dict[str, CertificateEnvelope] = {}
        #: label -> the claim labels that evidence declared as its premises.
        self.evidence_premises: dict[str, tuple[str, ...]] = {}
        #: id(statement) -> the context hash at that statement's position. Recorded during
        #: the ordered sweep so the second pass can ask what Γ was *there* rather than what
        #: it became by the end of the module -- which is the whole stale-context question.
        self.context_at: dict[int, str] = {}
        #: id(statement) -> the established claim labels at that statement's position.
        self.established_at: dict[int, tuple[str, ...]] = {}
        self._environment = None
        self._env_built = False
        self._ob_counter = 0
        #: The explicit evidence graph. The textual-order rule in `resolve_premises`
        #: remains as a cheap first line; this is the one that survives imports and any
        #: construction order that is not source order (directive E9).
        self.graph = EvidenceGraph()

    # -- 1. claim resolution ----------------------------------------------
    def resolve_claims(self) -> None:
        ordinal = 0
        for st in self.module.statements:
            label = getattr(st, "label", None)
            if not isinstance(st, _LABELLED) or not label:
                continue
            if label in self.claims:
                prev, _ = self.claims[label]
                self.diags.error(
                    "HML-R701",
                    f"claim {label!r} is declared twice",
                    st.span,
                    notes=[f"previous declaration at line {prev.span.line}"],
                    correction="use a distinct label",
                )
                continue
            cid = ClaimId(name=label, ordinal=ordinal)
            ordinal += 1
            self.claims[label] = (st, cid)
            st.claim_id = cid

    def resolve_premises(self) -> None:
        """Resolve premise labels, rejecting forward and circular references.

        A derivation may only cite claims declared *earlier in the module*.

        **This is a first line of defence, not the acyclicity argument.** An earlier
        version of this docstring claimed the ordering rule "gives acyclicity for free",
        and that is only true for a single module built in one pass from source order. It
        does not hold for imports, for batch graph construction, or for any assembly
        whose order is not textual order -- and it never saw the ``proved`` edge at all,
        which is the edge that closed the loop in the original goal-proves-itself
        exploit. The real check is :meth:`_validate_graph`, which walks every edge kind.
        """
        established: dict[str, ClaimId] = {}
        for st in self.module.statements:
            if isinstance(st, DeriveStmt):
                st.premise_ids = []
                for name in st.premises:
                    if name == st.label:
                        self.diags.error(
                            "HML-R702",
                            f"derivation {st.label!r} cites itself as a premise",
                            st.span,
                            correction="a derivation must rest on earlier claims",
                            notes=[
                                "circular provenance would make the reasoning graph "
                                "unsound: every claim would support itself"
                            ],
                        )
                        st.premise_ids.append(None)
                        continue
                    cid = established.get(name)
                    if cid is None:
                        known = ", ".join(sorted(established)) or "none yet"
                        later = name in self.claims
                        self.diags.error(
                            "HML-R703",
                            (
                                f"premise {name!r} is declared later in the module"
                                if later
                                else f"premise {name!r} is not a known claim"
                            ),
                            st.span,
                            found=name,
                            correction=(
                                "move the premise above this derivation"
                                if later
                                else f"claims in scope here: {known}"
                            ),
                            notes=[
                                "a derivation may only cite claims established before "
                                "it; this is what makes the reasoning graph acyclic"
                            ],
                        )
                        st.premise_ids.append(None)
                        continue
                    st.premise_ids.append(cid)
            label = getattr(st, "label", None)
            if isinstance(st, _LABELLED) and label and label in self.claims:
                established[label] = self.claims[label][1]

    # -- 2..4. the main sweep ---------------------------------------------
    def run(self) -> ReasoningResult:
        self.resolve_claims()
        self.resolve_premises()

        for st in self.module.statements:
            if isinstance(st, AssumeStmt):
                # An assumption is granted, not proved: that is what `assume` means.
                # It is therefore ESTABLISHED and may serve as a premise.
                self.env.assume(st.proposition, source_label=st.label)
                if st.label:
                    self.propositions[st.label] = st.proposition
                    self.graph.add_claim(
                        ClaimNode(st.label, EvidenceClass.ESTABLISHED)
                    )
            elif isinstance(st, (RequireStmt, ProveStmt, GoalStmt)):
                # `require`, `prove` and `goal` state things to be SHOWN. They are not
                # facts and they are not established, so they enter neither Γ nor the
                # premise pool -- they are recorded separately, for diagnostics only.
                #
                # This distinction is the whole ballgame, and an earlier version of this
                # file got it half right: it kept these three out of Γ (with a comment
                # naming the exact hazard) and then wrote them into `self.propositions`
                # anyway, which is the pool `_check_derivation` draws premises from. The
                # result was a module that compiled with zero diagnostics and reported
                # `1.0 = 2.0` as PROVED:
                #
                #     goal   g1 : 1.0 = 2.0
                #     derive d1 : 2.0 = 1.0 from g1 by symmetry
                #     derive d2 : 1.0 = 2.0 from d1 by symmetry
                #     proved g1 by d2
                #
                # The kernel was blameless -- both steps really are valid applications of
                # symmetry. The defect was admitting an unestablished claim as a premise.
                # Guarding one channel and not the other is worse than guarding neither,
                # because it reads as though the hazard was handled.
                # Regression: tests/reasoning/test_circularity.py.
                if st.label:
                    self.unestablished[st.label] = st
                    self.graph.add_claim(
                        ClaimNode(st.label, EvidenceClass.NOT_EVIDENCE)
                    )
                if isinstance(st, GoalStmt):
                    self.result.goal_status[st.label] = GoalStatus.OPEN
            elif isinstance(st, DeriveStmt):
                self._check_derivation(st)
            elif isinstance(st, EvidenceStmt):
                self._check_evidence(st)
            elif isinstance(st, UndeterminedStmt):
                # Snapshot Γ *here*. The adjudication runs in the second pass, but the
                # question it must answer is whether the certificate's context matches the
                # context at this point in the module -- not the context after every later
                # statement has been read.
                self.context_at[id(st)] = self._context_hash()

        for st in self.module.statements:
            if isinstance(st, ProvedStmt):
                self._adjudicate(st)
            elif isinstance(st, UndeterminedStmt):
                self._adjudicate_undetermined(st)

        self._validate_graph()

        for label, (st, _) in self.claims.items():
            if isinstance(st, GoalStmt):
                self.result.goal_status.setdefault(label, GoalStatus.OPEN)
                st.status = self.result.goal_status[label]
        return self.result

    def _validate_graph(self) -> None:
        """Run the explicit evidence-graph validator and report any violation.

        This is a **second, independent** check, not a replacement for the rules already
        enforced during the sweep. If it ever fires, one of two things is true: a defect
        exists in the incremental rules, or a construction path was added that those
        rules do not cover (an import, a batch build). Both are worth an error rather
        than a silent pass, which is why the diagnostic names the invariant.
        """
        verified = [
            label
            for label, status in self.result.derivation_status.items()
            if status == DerivationStatus.VERIFIED
        ]
        for v in self.graph.validate(verified_labels=verified):
            self.diags.error(
                "HML-R714",
                f"evidence-graph invariant {v.invariant} violated: {v.message}",
                self._span_for(v.labels),
                notes=[
                    INVARIANTS.get(v.invariant, ""),
                    "this is the independent graph validator, not the incremental rules; "
                    "if it fires, the incremental rules missed a construction path",
                ],
            )

    def _span_for(self, labels: tuple[str, ...]):
        for label in labels:
            entry = self.claims.get(label)
            if entry is not None:
                return entry[0].span
        return self.module.span

    def _next_obligation_id(self) -> str:
        self._ob_counter += 1
        return f"o{self._ob_counter}"

    # -- context identity --------------------------------------------------
    def _context_hash(self) -> str:
        """Identity of Γ right now: a digest over the canonical identity of every claim
        currently usable as a premise.

        ``self.propositions`` is exactly "what may support a conclusion here", which is
        the right notion of Γ. It includes PROVISIONAL claims, and that is the
        conservative direction: a larger Γ makes an underdetermination certificate
        *harder* to satisfy, never easier, because both models must satisfy every member.
        """
        from ..backends.canonical import expr_identity

        return context_hash([expr_identity(p) for p in self.propositions.values()])

    def _environment_for_checkers(self):
        """The exact-evaluation environment, built once and reused.

        Built lazily because most modules contain no ``evidence`` statement and should not
        pay for one.
        """
        if not self._env_built:
            self._env_built = True
            try:
                from ..verification.obligations.evaluate import build_environment

                self._environment = build_environment(self.module, self.symbols)
            except Exception:  # noqa: BLE001 -- no environment means checkers fail closed
                self._environment = None
        return self._environment

    def _assumptions_in_scope(self) -> list[tuple[str, Expr]]:
        """Every assumption anywhere in the module, including inside ``scope`` frames.

        A deliberate superset -- see ``side_conditions._eigenvariable`` for why the
        eigenvariable condition is checked against all of them rather than the premise
        closure.
        """
        out: list[tuple[str, Expr]] = []
        for node in walk(self.module):
            if isinstance(node, AssumeStmt) and node.proposition is not None:
                out.append((node.label or "<unlabelled>", node.proposition))
        return out

    # -- the certificate boundary -----------------------------------------
    def _check_evidence(self, st: EvidenceStmt) -> None:
        """Validate one ``evidence`` statement through the trusted checker registry.

        Nothing here decides any mathematics. It assembles the envelope from what the
        author wrote, hands it to :func:`reasoning.certificates.check`, and records the
        verdict. Every way this can fail is a rejection.
        """
        from ..backends.canonical import expr_identity

        if any(p is None for p in st.premise_ids):
            self._reject_evidence(st, "one or more premises could not be resolved")
            return

        premise_pairs: list[tuple[str, Expr]] = []
        for name in st.premises:
            unestablished = self.unestablished.get(name)
            if unestablished is not None:
                self.diags.error(
                    "HML-R716",
                    f"{name!r} is not an established fact and cannot support evidence",
                    st.span,
                    found=name,
                    correction="cite an assumption, a verified derivation, or valid evidence",
                    notes=[
                        "a goal, requirement, claim or non-entailment result states "
                        "something to be shown; none of them establishes anything"
                    ],
                )
                self._reject_evidence(st, f"premise {name!r} is not established")
                return
            prop = self.propositions.get(name)
            if prop is None:
                self._reject_evidence(st, f"premise {name!r} carries no proposition")
                return
            premise_pairs.append((name, prop))

        judgement = (
            JudgementKind.ENTAILS
            if st.judgement == "ENTAILS"
            else JudgementKind.DETERMINES_NEITHER
        )
        ctx_hash = self._context_hash()

        # A non-entailment certificate must be issued against the WHOLE context. Γ ⊭ P for
        # a subset of Γ says nothing about Γ itself, because entailment is monotone:
        # adding premises can only increase what follows. An entailment certificate has no
        # such requirement -- proving P from fewer premises is strictly stronger.
        if judgement is JudgementKind.DETERMINES_NEITHER:
            declared = set(st.premises)
            missing = [lbl for lbl in self.propositions if lbl not in declared]
            if missing:
                self.diags.error(
                    "HML-R717",
                    (
                        f"evidence {st.label!r} claims non-entailment but does not rest on "
                        f"every established claim in scope: {', '.join(sorted(missing))} "
                        f"{'is' if len(missing) == 1 else 'are'} missing"
                    ),
                    st.span,
                    correction=f"add {', '.join(sorted(missing))} to the 'from' list",
                    notes=[
                        "entailment is monotone: a context that settles nothing may "
                        "settle the target once another premise is added, so a "
                        "non-entailment result must name the whole context",
                    ],
                )
                self._reject_evidence(st, "the certificate does not cover the whole context")
                return

        envelope = CertificateEnvelope(
            certificate_type=st.checker,
            certificate_version=1,
            checker=st.checker,
            judgement=judgement,
            claim_hash=expr_identity(st.proposition),
            context_hash=ctx_hash,
            premise_hashes=tuple(expr_identity(p) for _, p in premise_pairs),
            span=st.span,
        )
        payload = {a.role: a.value for a in st.checker_args}
        payload["__claim__"] = st.proposition
        checker_ctx = CheckerContext(
            premises=tuple(premise_pairs),
            payload=payload,
            environment=self._environment_for_checkers(),
            declared_types={},
        )

        evidence, reason = check_certificate(
            envelope, st.proposition, checker_ctx, current_context_hash=ctx_hash
        )
        if evidence is None:
            from ..backends.hml import render_expr

            known = ", ".join(_checker_names()) or "none"
            self.diags.error(
                "HML-R718",
                f"evidence {st.label!r} is REJECTED: {reason}",
                st.span,
                found=st.checker,
                correction=(
                    f"registered checkers: {known}"
                    if st.checker not in _checker_registry()
                    else f"the checker could not validate {render_expr(st.proposition)}"
                ),
                notes=[
                    "checkers come from a static trusted registry; source cannot define "
                    "one, because a user-supplied checker could certify anything",
                ],
            )
            self._reject_evidence(st, reason)
            return

        st.status = EvidenceStatus.VALID
        self.result.evidence_status[st.label] = st.status
        self.certificates[st.label] = envelope
        self.evidence_premises[st.label] = tuple(st.premises)

        if judgement is JudgementKind.ENTAILS:
            # Checked evidence for a proposition is ordinary evidence: usable as a premise.
            self.propositions[st.label] = st.proposition
            self.graph.add_claim(ClaimNode(st.label, EvidenceClass.ESTABLISHED))
        else:
            # "The premises settle neither P nor not-P" is a statement about the theory,
            # NOT an assertion of P. Letting it be a premise would be the worst failure
            # available here -- it would turn "we cannot tell" into a fact. NOT_EVIDENCE
            # is what stops that, and E2 in the graph validator enforces it independently.
            self.unestablished[st.label] = st
            self.graph.add_claim(ClaimNode(st.label, EvidenceClass.NOT_EVIDENCE))
        for premise in st.premises:
            self.graph.add_edge(st.label, premise, EdgeKind.PREMISE)

    def _reject_evidence(self, st: EvidenceStmt, reason: str) -> None:
        st.status = EvidenceStatus.REJECTED
        st.rejection_reason = reason
        self.result.evidence_status[st.label] = st.status
        self.unestablished.setdefault(st.label, st)
        if self.graph.node(st.label) is None:
            self.graph.add_claim(ClaimNode(st.label, EvidenceClass.NOT_EVIDENCE))

    def _check_derivation(self, st: DeriveStmt) -> None:
        from ..backends.canonical import expr_identity

        if any(p is None for p in st.premise_ids):
            self._reject(st, "one or more premises could not be resolved")
            return

        premise_props: list[Expr] = []
        inherited: list[ReasoningObligation] = []
        for name in st.premises:
            unestablished = self.unestablished.get(name)
            if unestablished is not None:
                kind = _unestablished_kind(unestablished)
                self.diags.error(
                    "HML-R712",
                    f"{name!r} is a {kind}, not an established fact, and cannot be a premise",
                    st.span,
                    found=name,
                    correction=(
                        f"derive {name!r} first, or state it as an assumption if it is "
                        f"genuinely being granted"
                    ),
                    notes=[
                        (
                            "a non-entailment result says the premises settle NEITHER the "
                            "proposition nor its negation; it is emphatically not the "
                            "proposition, and using it as one would turn 'we cannot tell' "
                            "into a fact"
                            if kind == "non-entailment result"
                            else f"a {kind} states something to be SHOWN; using it to "
                            f"support a derivation would make the derivation support itself"
                        ),
                        "only `assume`, a checked `derive` and valid `entails` evidence "
                        "are established",
                    ],
                )
                self._reject(st, f"premise {name!r} is not established")
                return
            prop = self.propositions.get(name)
            if prop is None:
                self._reject(st, f"premise {name!r} carries no proposition")
                return
            premise_props.append(prop)
            # A step resting on a premise with an open obligation inherits it: the
            # conclusion is no better established than the weakest thing it stands on.
            inherited.extend(self.pending.get(name, ()))

        args = {a.role: a.value for a in st.rule_args}
        application = kernel.apply(st.rule, premise_props, args)

        if not application.ok:
            if st.rule not in kernel.RULES:
                self.diags.error(
                    "HML-R704",
                    f"{st.rule!r} is not a rule in the trusted kernel",
                    st.span,
                    found=st.rule,
                    correction=f"available rules: {', '.join(kernel.rule_names())}",
                    notes=[
                        "HML does not accept user-defined trusted inference rules; a "
                        "rule the kernel cannot check could certify anything"
                    ],
                )
            else:
                self.diags.error(
                    "HML-R705",
                    f"rule {st.rule!r} does not apply here",
                    st.span,
                    notes=[application.reason or "no reason recorded"],
                    correction=kernel.RULES[st.rule].shape,
                )
            self._reject(st, application.reason or "rule did not apply")
            return

        assert application.conclusion is not None
        # THE soundness check. The kernel built `application.conclusion` without ever
        # seeing `st.conclusion`; if they are canonically identical, the author's step
        # is the kernel's step.
        if expr_identity(application.conclusion) != expr_identity(st.conclusion):
            from ..backends.hml import render_expr

            self.diags.error(
                "HML-R706",
                f"the stated conclusion is not what {st.rule!r} yields",
                st.span,
                found=render_expr(st.conclusion),
                expected=render_expr(application.conclusion),
                correction=f"write the conclusion {st.rule!r} licenses, or use another rule",
                notes=[
                    "the conclusion is compared under canonical identity, so this is "
                    "not a formatting difference"
                ],
            )
            self._reject(st, "stated conclusion differs from the rule's conclusion")
            return

        # The rule's CONTEXT-DEPENDENT conditions. The kernel could not check these -- the
        # eigenvariable condition asks about every assumption in scope, domain conformance
        # asks the type environment -- so it named them and this is where they are
        # answered. An unknown name rejects, so a rule can never be admitted by a guard
        # nobody implemented.
        spec = kernel.RULES[st.rule]
        if spec.side_conditions:
            ok, why = _evaluate_side_conditions(
                spec.side_conditions,
                SideConditionContext(
                    rule=st.rule,
                    label=st.label,
                    premises=premise_props,
                    args=args,
                    assumptions=self._assumptions_in_scope(),
                ),
            )
            if not ok:
                self.diags.error(
                    "HML-R719",
                    f"derivation {st.label!r} is REJECTED: {why}",
                    st.span,
                    correction=kernel.RULES[st.rule].shape,
                    notes=[
                        "the rule applied structurally; its side condition did not hold",
                        kernel.RULES[st.rule].doc,
                    ],
                )
                self._reject(st, why)
                return

        # CHECKED. Now the obligations decide whether it reaches VERIFIED.
        #
        # Definedness obligations come FIRST and come from the TERMS, not from the rule.
        # Keying them on the rule was a critical soundness hole: `divide_both_sides`
        # declared `k != 0`, so writing the same step as
        # `multiply_both_sides(by := 1.0 / 0.0)` reached VERIFIED with a literal division
        # by zero in the certified statement. A rule cannot evade a requirement it does
        # not know about, because the requirement is found in the expression.
        obligations: list[ReasoningObligation] = []
        rule_arg_values = [a.value for a in st.rule_args]
        for term in [st.conclusion, *rule_arg_values]:
            for pre in preconditions_of(term):
                obligations.append(
                    ReasoningObligation(
                        id=self._next_obligation_id(),
                        proposition=pre.proposition,
                        generated_by=st.label,
                        reason=pre.reason,
                        mandatory=pre.mandatory,
                    )
                )

        for prop, reason, mandatory in application.obligations:
            obligations.append(
                ReasoningObligation(
                    id=self._next_obligation_id(),
                    proposition=prop,
                    generated_by=st.label,
                    reason=reason,
                    mandatory=mandatory,
                )
            )

        # The same requirement stated twice is one requirement. `y / k = 2.0 * x / k`
        # contains two divisions by `k`, and reporting `k != 0` three times (twice from
        # the terms, once from the rule) is noise that trains authors to stop reading
        # obligations. Deduplicated by canonical identity, which is the language's own
        # notion of "the same proposition" rather than a second one.
        deduped: list[ReasoningObligation] = []
        seen_props: set[str] = set()
        for ob in obligations:
            key = expr_identity(ob.proposition)
            if key in seen_props:
                continue
            seen_props.add(key)
            deduped.append(ob)
        obligations = deduped

        # Discharge and refutation run over EVERY obligation, whichever channel produced
        # it. Doing this per-channel is how the definedness obligations were left
        # permanently OPEN on their first outing: they were appended to the list but the
        # `entails` call lived inside the rule-obligation loop, so nothing ever asked Γ
        # about them. One loop, one policy.
        for ob in obligations:
            hit = self.env.entails(ob.proposition)
            if hit is not None:
                ob.status = ObligationStatus.DISCHARGED
                ob.discharged_by = hit.source_label or "an assumption in scope"
            elif decides_false(ob.proposition):
                # An obligation decidably FALSE is FAILED, not OPEN. Reporting a known
                # falsehood as ignorance is strictly worse than saying nothing, and it is
                # what let `1.0 / 0.0` look merely unproven (D-038 V5).
                ob.status = ObligationStatus.FAILED
        self.result.obligations.extend(obligations)

        failed = [o for o in obligations if o.status is ObligationStatus.FAILED]
        if failed:
            from ..backends.hml import render_expr

            for o in failed:
                self.diags.error(
                    "HML-R715",
                    (
                        f"derivation {st.label!r} is REJECTED: "
                        f"{render_expr(o.proposition)} is false"
                    ),
                    st.span,
                    notes=[
                        f"obligation {o.id} ({o.reason}) is refuted, not merely open",
                        "the step mentions an operation that is undefined on the value "
                        "it is applied to",
                    ],
                    correction="the expression is not defined; it must be rewritten",
                )
            self._reject(st, "a definedness obligation is refuted")
            self.pending[st.label] = failed
            return

        self._finalise_status(st, obligations, inherited)
        self.propositions[st.label] = st.conclusion

    def _finalise_status(
        self,
        st: DeriveStmt,
        obligations: list[ReasoningObligation],
        inherited: list[ReasoningObligation],
    ) -> None:
        """The ONLY place VERIFIED is ever assigned.

        ``inherited`` carries the still-open obligations of this step's premises. They
        are counted but not re-reported: a chain of ten steps resting on one undischarged
        `k != 0` should say so once, at the step that generated it, and then decline to
        certify the nine that follow.
        """
        own = [
            o
            for o in obligations
            if o.mandatory and o.status != ObligationStatus.DISCHARGED
        ]
        still_open = [
            o
            for o in inherited
            if o.mandatory and o.status != ObligationStatus.DISCHARGED
        ]
        undischarged = own
        if undischarged:
            st.status = DerivationStatus.CHECKED
            from ..backends.hml import render_expr

            for o in undischarged:
                self.diags.warn(
                    "HML-R707",
                    (
                        f"derivation {st.label!r} is CHECKED but not VERIFIED: "
                        f"{render_expr(o.proposition)} is not established"
                    ),
                    st.span,
                    correction=(
                        f"add 'assume {render_expr(o.proposition)}' above this "
                        f"derivation, or derive it"
                    ),
                    notes=[
                        f"obligation {o.id} ({o.reason}) generated by rule {st.rule!r}",
                        "the step is structurally correct; its side condition is not "
                        "discharged, so the result is not certified",
                    ],
                )
        elif still_open:
            # Structurally correct, own side conditions met, but standing on a premise
            # whose obligation nobody discharged. Not certified.
            st.status = DerivationStatus.CHECKED
            from ..backends.hml import render_expr

            first = still_open[0]
            self.diags.warn(
                "HML-R713",
                (
                    f"derivation {st.label!r} is CHECKED but not VERIFIED: it rests on "
                    f"{first.generated_by!r}, whose obligation "
                    f"{render_expr(first.proposition)} is not established"
                ),
                st.span,
                correction=(
                    f"discharge the obligation on {first.generated_by!r} and this step "
                    f"is certified too"
                ),
                notes=[
                    "a conclusion is no better established than the weakest premise it "
                    "stands on"
                ],
            )
        else:
            st.status = DerivationStatus.VERIFIED
        self.pending[st.label] = own + still_open
        self.result.derivation_status[st.label] = st.status

        # Record this step in the explicit evidence graph. A VERIFIED derivation is
        # ESTABLISHED; a CHECKED one is PROVISIONAL -- usable, but only by carrying its
        # obligations forward, which `own` supplies to `transitive_open_obligations`.
        self.graph.add_claim(
            ClaimNode(
                label=st.label,
                evidence_class=(
                    EvidenceClass.ESTABLISHED
                    if st.status == DerivationStatus.VERIFIED
                    else EvidenceClass.PROVISIONAL
                ),
                own_open_obligations=tuple(o.id for o in own),
            )
        )
        for premise in st.premises:
            self.graph.add_edge(st.label, premise, EdgeKind.PREMISE)

    def _reject(self, st: DeriveStmt, reason: str) -> None:
        st.status = DerivationStatus.REJECTED
        st.rejection_reason = reason
        self.result.derivation_status[st.label] = st.status

    # -- 5. goal adjudication ---------------------------------------------
    def _adjudicate(self, st: ProvedStmt) -> None:
        from ..backends.canonical import expr_identity

        goal_entry = self.claims.get(st.goal)
        if goal_entry is None or not isinstance(goal_entry[0], GoalStmt):
            self.diags.error(
                "HML-R708",
                f"{st.goal!r} is not a declared goal",
                st.span,
                found=st.goal,
                correction="declare it first, e.g. 'goal g1 : <proposition>'",
            )
            return
        goal_stmt = goal_entry[0]
        st.goal_id = goal_entry[1]

        der_entry = self.claims.get(st.derivation)
        if der_entry is None or not isinstance(der_entry[0], DeriveStmt):
            self.diags.error(
                "HML-R709",
                f"{st.derivation!r} is not a declared derivation",
                st.span,
                found=st.derivation,
                correction="reference a 'derive' statement",
            )
            self.result.goal_status[st.goal] = GoalStatus.UNSUBSTANTIATED
            return
        derivation = der_entry[0]
        st.derivation_id = der_entry[1]

        if derivation.status != DerivationStatus.VERIFIED:
            self.diags.error(
                "HML-R710",
                (
                    f"goal {st.goal!r} is not proved: derivation {st.derivation!r} is "
                    f"{derivation.status}, not VERIFIED"
                ),
                st.span,
                found=derivation.status,
                expected=DerivationStatus.VERIFIED,
                correction=(
                    "discharge the derivation's open obligations"
                    if derivation.status == DerivationStatus.CHECKED
                    else "repair the derivation"
                ),
                notes=[
                    "a proof claim is adjudicated, not accepted; writing 'proved' does "
                    "not make a goal proved"
                ],
            )
            self.result.goal_status[st.goal] = GoalStatus.UNSUBSTANTIATED
            goal_stmt.status = GoalStatus.UNSUBSTANTIATED
            return

        if expr_identity(derivation.conclusion) != expr_identity(goal_stmt.proposition):
            from ..backends.hml import render_expr

            self.diags.error(
                "HML-R711",
                (
                    f"derivation {st.derivation!r} does not conclude goal {st.goal!r}"
                ),
                st.span,
                found=render_expr(derivation.conclusion),
                expected=render_expr(goal_stmt.proposition),
                correction="derive the goal's proposition exactly, or restate the goal",
            )
            self.result.goal_status[st.goal] = GoalStatus.UNSUBSTANTIATED
            goal_stmt.status = GoalStatus.UNSUBSTANTIATED
            return

        self.result.goal_status[st.goal] = GoalStatus.PROVED
        goal_stmt.status = GoalStatus.PROVED
        self.result.adjudications[st.goal] = Adjudication(
            goal=st.goal,
            verdict=EntailmentVerdict.ENTAILED,
            target_hash=expr_identity(goal_stmt.proposition),
            context_hash=self._context_hash(),
            premise_hashes=tuple(
                expr_identity(self.propositions[p])
                for p in derivation.premises
                if p in self.propositions
            ),
            support=st.derivation,
        )
        # Record the proof edge. This is the edge the premise-only view could not see,
        # and it is the one that closes the loop when a goal is used to support the
        # derivation that proves it: `d1 --premise--> g1` plus `g1 --proof--> d1` is a
        # cycle, which E1 reports even if the incremental premise rule were ever bypassed.
        self.graph.add_edge(st.goal, st.derivation, EdgeKind.PROOF)


    # -- 6. underdetermination adjudication --------------------------------
    def _adjudicate_undetermined(self, st: UndeterminedStmt) -> None:
        """``undetermined g by e``. Adjudicated with exactly the suspicion ``proved`` gets.

        Writing the statement does not make the goal underdetermined. Four things must
        hold, and each failure leaves the goal OPEN -- **never** UNDERDETERMINED, because
        a failed claim of underdetermination is ignorance, and ignorance is the one thing
        this status must never be able to record.
        """
        from ..backends.canonical import expr_identity

        goal_entry = self.claims.get(st.goal)
        if goal_entry is None or not isinstance(goal_entry[0], GoalStmt):
            self.diags.error(
                "HML-R720",
                f"{st.goal!r} is not a declared goal",
                st.span,
                found=st.goal,
                correction="declare it first, e.g. 'goal g1 : <proposition>'",
            )
            return
        goal_stmt = goal_entry[0]
        st.goal_id = goal_entry[1]

        ev_entry = self.claims.get(st.evidence)
        if ev_entry is None or not isinstance(ev_entry[0], EvidenceStmt):
            self.diags.error(
                "HML-R721",
                f"{st.evidence!r} is not a declared evidence statement",
                st.span,
                found=st.evidence,
                correction="reference an 'evidence' statement",
            )
            self._unknown(st.goal, goal_stmt, f"{st.evidence!r} is not evidence")
            return
        ev = ev_entry[0]
        st.evidence_id = ev_entry[1]

        if ev.status != EvidenceStatus.VALID:
            self.diags.error(
                "HML-R722",
                (
                    f"goal {st.goal!r} is not underdetermined: evidence {st.evidence!r} is "
                    f"{ev.status}, not VALID"
                ),
                st.span,
                found=ev.status,
                expected=EvidenceStatus.VALID,
                correction="repair the certificate",
                notes=[
                    "an underdetermination claim is adjudicated, not accepted; a "
                    "certificate nobody could validate establishes nothing at all"
                ],
            )
            self._unknown(st.goal, goal_stmt, "the certificate is not valid")
            return

        if ev.judgement != "DETERMINES_NEITHER":
            self.diags.error(
                "HML-R723",
                (
                    f"evidence {st.evidence!r} carries an 'entails' judgement and cannot "
                    f"show that goal {st.goal!r} is underdetermined"
                ),
                st.span,
                correction=f"use 'determines_neither' evidence, or 'proved {st.goal} by ...'",
                notes=[
                    "establishing a proposition and showing that the premises settle "
                    "neither it nor its negation are opposite results"
                ],
            )
            self._unknown(st.goal, goal_stmt, "the evidence is not a non-entailment result")
            return

        if expr_identity(ev.proposition) != expr_identity(goal_stmt.proposition):
            from ..backends.hml import render_expr

            self.diags.error(
                "HML-R724",
                f"evidence {st.evidence!r} is not about goal {st.goal!r}",
                st.span,
                found=render_expr(ev.proposition),
                expected=render_expr(goal_stmt.proposition),
                correction="certify the goal's proposition exactly, or restate the goal",
            )
            self._unknown(st.goal, goal_stmt, "the certificate is about a different claim")
            return

        # THE stale-context check. The certificate was issued against Γ as it stood at the
        # `evidence` statement; here we ask what Γ is at THIS point. Non-entailment does
        # not survive a premise being added, so a certificate issued earlier in the module
        # must not be spendable after the context has moved on.
        envelope = self.certificates[st.evidence]
        here = self.context_at.get(id(st))
        if here is not None and here != envelope.context_hash:
            self.diags.error(
                "HML-R725",
                (
                    f"evidence {st.evidence!r} was certified against a different context "
                    f"than the one in scope at this point"
                ),
                st.span,
                correction=(
                    "move the claim next to its evidence, or re-certify against the "
                    "current premises"
                ),
                notes=[
                    "entailment is monotone: premises added after the certificate was "
                    "issued may settle the target, so the earlier result no longer "
                    "applies",
                    "this is not a formatting difference -- the context genuinely changed",
                ],
            )
            self._unknown(st.goal, goal_stmt, "the certificate's context is stale")
            return

        self.result.goal_status[st.goal] = GoalStatus.UNDERDETERMINED
        goal_stmt.status = GoalStatus.UNDERDETERMINED
        self.result.adjudications[st.goal] = Adjudication(
            goal=st.goal,
            verdict=EntailmentVerdict.UNDERDETERMINED,
            target_hash=envelope.claim_hash,
            context_hash=envelope.context_hash,
            premise_hashes=envelope.premise_hashes,
            support=st.evidence,
            checker=envelope.checker,
        )
        # The same edge `proved` records, and for the same reason: it closes the loop when
        # a goal is used to support the evidence that settles it, so E1 reports the cycle.
        self.graph.add_edge(st.goal, st.evidence, EdgeKind.PROOF)

    def _unknown(self, goal: str, goal_stmt: GoalStmt, reason: str) -> None:
        """Record a failed underdetermination claim as UNKNOWN -- never UNDERDETERMINED.

        The goal stays OPEN. This is the projection boundary doing its job: a claim that
        did not survive adjudication leaves exactly as much knowledge as there was before
        it was made, which is none.
        """
        self.result.goal_status.setdefault(goal, GoalStatus.OPEN)
        goal_stmt.status = self.result.goal_status[goal]
        self.result.adjudications[goal] = Adjudication(
            goal=goal,
            verdict=EntailmentVerdict.UNKNOWN,
            target_hash="",
            context_hash="",
            reason=reason,
        )


def check_reasoning(
    module: Module, diags: DiagnosticBag, symbols: object = None
) -> ReasoningResult:
    """Check a module's reasoning.

    ``symbols`` is optional so every existing caller keeps working; it is used to build
    the exact-evaluation environment that certificate checkers run in. Without it,
    checkers that need declared domains fail closed rather than guessing.
    """
    return _ReasoningChecker(module, diags, symbols).run()
